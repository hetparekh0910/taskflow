const { chromium } = require('playwright')
const OUT = __dirname
;(async () => {
  const b = await chromium.launch()
  const pg = await (await b.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 })).newPage()
  const errs = []
  pg.on('pageerror', e => errs.push('pageerror: ' + e.message))
  pg.on('console', m => { if (m.type() === 'error') errs.push('console: ' + m.text()) })
  await pg.goto('http://localhost:5173/login')
  await pg.getByRole('button', { name: /Alice/ }).click()
  await pg.getByRole('button', { name: 'Sign in' }).click()
  await pg.waitForURL(/\/w\/acme-robotics/)
  await pg.screenshot({ path: OUT + '/1-dashboard.png' })
  await pg.getByRole('link', { name: /Web Storefront/ }).click()
  await pg.waitForSelector('[data-testid^="card-"]')
  await pg.screenshot({ path: OUT + '/2-board.png' })
  const todo = pg.locator('section[aria-label="To Do"]')
  const prog = pg.locator('section[aria-label="In Progress"]')
  const before = { todo: await todo.locator('.issue-card').count(), prog: await prog.locator('.issue-card').count() }
  const card = todo.locator('.issue-card').first()
  const key = await card.locator('.mono').first().innerText()
  const cb = await card.boundingBox(), pb = await prog.locator('.column-body').boundingBox()
  await pg.mouse.move(cb.x + 40, cb.y + 20); await pg.mouse.down()
  await pg.mouse.move(cb.x + 60, cb.y + 40, { steps: 5 })
  await pg.mouse.move(pb.x + 100, pb.y + 30, { steps: 15 })
  await pg.mouse.up()
  await pg.waitForTimeout(1200)
  const after = { todo: await todo.locator('.issue-card').count(), prog: await prog.locator('.issue-card').count() }
  console.log('moved', key, JSON.stringify(before), '->', JSON.stringify(after))
  await pg.screenshot({ path: OUT + '/3-after-drag.png' })
  await pg.reload(); await pg.waitForSelector('[data-testid^="card-"]')
  const persisted = await pg.locator('section[aria-label="In Progress"]').locator('.issue-card', { hasText: key }).count()
  console.log('persisted after reload:', persisted === 1)
  await pg.locator('.issue-card', { hasText: key }).locator('.issue-title').click()
  await pg.waitForSelector('.drawer'); await pg.waitForTimeout(500)
  await pg.screenshot({ path: OUT + '/4-drawer.png' })
  console.log('errors:', errs.length ? errs : 'none')
  await b.close()
})().catch(e => { console.error('FAIL', e.message); process.exit(1) })
