import { useState } from 'react'
import { useMutation, useQuery } from '@tanstack/react-query'
import { api } from '../api/client'
import { Button, ErrorBox, Loading, errMsg, useToast } from '../components/ui'
import { useWs } from '../layout/WorkspaceContext'

interface Report { workspace: string; period_days: number; totals: { created: number; resolved: number; open: number; overdue: number }
  projects: { key: string; name: string; open: number; created: number; resolved: number }[]; top_contributors: { name: string; resolved: number }[]; active_sprints: { project: string; name: string; ends: string | null }[] }

export default function Reports() {
  const { p, can, slug } = useWs(); const toast = useToast()
  const [days, setDays] = useState(7)
  const { data, isLoading, error } = useQuery({ queryKey: ['report', slug, days], queryFn: () => api<Report>(p('/reports/weekly/'), { params: { days } }) })
  const send = useMutation({ mutationFn: () => api(p('/reports/weekly/'), { method: 'POST' }), onSuccess: () => toast('Report queued: owners and admins will receive it by email'), onError: (e) => toast(errMsg(e), true) })
  if (isLoading) return <Loading />
  if (error || !data) return <ErrorBox error={error} />
  const t = data.totals
  return (
    <>
      <div className="page-head"><div><h1>Reports</h1><div className="muted">Generated by a background job every week and emailed to owners and admins.</div></div>
        <div className="row"><select className="select sm" value={days} onChange={(e) => setDays(Number(e.target.value))}><option value={7}>Last 7 days</option><option value={14}>Last 14 days</option><option value={30}>Last 30 days</option></select>
          {can('admin') && <Button variant="primary" disabled={send.isPending} onClick={() => send.mutate()}>✉ Email this report now</Button>}</div></div>
      <div className="grid stats" style={{ marginBottom: 16 }}>
        {[['Created', t.created], ['Resolved', t.resolved], ['Open now', t.open], ['Overdue', t.overdue]].map(([l, v]) => <div key={l} className="card pad stat"><div className="v">{v}</div><div className="l">{l}</div></div>)}</div>
      <div className="grid two">
        <div className="card pad"><h3>By project</h3><table className="table"><thead><tr><th>Project</th><th>Open</th><th>Created</th><th>Resolved</th></tr></thead><tbody>
          {data.projects.map((x) => <tr key={x.key}><td><span className="badge">{x.key}</span> {x.name}</td><td>{x.open}</td><td>+{x.created}</td><td>−{x.resolved}</td></tr>)}</tbody></table></div>
        <div className="card pad col"><h3>Top contributors</h3>{data.top_contributors.length ? data.top_contributors.map((c, i) => <div key={c.name} className="row spread"><span>{i + 1}. {c.name}</span><span className="badge success">{c.resolved} resolved</span></div>) : <div className="muted">No resolved issues in this period.</div>}
          <h3 style={{ marginTop: 12 }}>Active sprints</h3>{data.active_sprints.length ? data.active_sprints.map((s) => <div key={s.name} className="row spread"><span>{s.project} · {s.name}</span><span className="muted small">ends {s.ends}</span></div>) : <div className="muted">None running.</div>}</div>
      </div>
    </>
  )
}
